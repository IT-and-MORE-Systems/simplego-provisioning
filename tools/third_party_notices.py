def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--offline",
         "--filter-platform", TARGET],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def shipped(meta):
    """Crates compiled into the binary: normal dependencies, transitively,
    without proc macros and build-only crates."""
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        x = stack.pop()
        for d in nodes[x]["deps"]:
            if not any(k["kind"] is None for k in d["dep_kinds"]):
                continue
            p = pk[d["pkg"]]
            if any("proc-macro" in t["kind"] for t in p["targets"]):
                continue
            if d["pkg"] not in seen:
                seen.add(d["pkg"])
                stack.append(d["pkg"])
    return sorted((pk[i] for i in seen), key=lambda p: (p["name"], p["version"]))


def all_locked(meta):
    """Every crate of the locked tree for the release target, with its role."""
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    role = {}
    def walk(start, kinds, name):
        stack = [start]
        while stack:
            x = stack.pop()
            for d in nodes[x]["deps"]:
                ks = {k["kind"] for k in d["dep_kinds"]}
                if x == start and not ks & kinds:
                    continue
                if x != start and not ks & {None, "build"}:
                    continue
                if d["pkg"] not in role:
                    role[d["pkg"]] = name
                    stack.append(d["pkg"])
    ship = {p["id"] for p in shipped(meta)}
    for i in ship:
        role[i] = "in the binary"
    walk(root, {None, "build"}, "build time only")
    walk(root, {"dev"}, "tests only")
    return sorted(((pk[i], r) for i, r in role.items()), key=lambda t: (t[0]["name"], t[0]["version"]))


def source_url(p):
    return p.get("repository") or f"https://crates.io/crates/{p['name']}"


def licence_files(p):
    d = pathlib.Path(p["manifest_path"]).parent
    out = []
    for f in sorted(d.iterdir()):
        if f.is_file() and LICENSE_FILE.match(f.name):
            out.append((f.name, f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip() + "\n"))
    return out


def notices(meta):
    crates = shipped(meta)
    texts = {}
    rows = []
    missing = []
    for p in crates:
        refs = []
        files = licence_files(p)
        if not files:
            missing.append(p["name"])
        for name, t in files:
            h = hashlib.sha256(t.encode()).hexdigest()[:12]
            texts.setdefault(h, (t, []))[1].append(f"{p['name']} {p['version']} ({name})")
            refs.append(f"[{h}](#text-{h})")
        rows.append(f"| {p['name']} | {p['version']} | {p.get('license') or '?'} | {source_url(p)} | {', '.join(refs) or 'licence field only'} |")
    lines = [
        "# Third-party notices",
        "",
        "SimpleGo Provisioning (`sxprov`) is licensed under the GNU AGPL-3.0-or-later",
        "(see LICENSE). The release binary also contains the following third-party",
        "software, each under its own licence. Generated by",
        "`tools/third_party_notices.py` from `Cargo.lock`; do not edit by hand.",
        "",
        "## Linked runtime",
        "",
        "| Component | Licence | Source |",
        "|---|---|---|",
        "| Rust standard library (`std`, `core`, `alloc`) | MIT OR Apache-2.0 | https://github.com/rust-lang/rust |",
        "| musl libc (statically linked) | MIT | https://musl.libc.org |",
        "",
        "## Crates",
        "",
        "| Crate | Version | Licence | Source | Licence text |",
        "|---|---|---|---|---|",
        *rows,
        "",
    ]
    if missing:
        lines += ["Crates that ship no licence file (their `license` field applies; the",
                  "standard text of that licence is among the texts below): " + ", ".join(missing) + ".", ""]
    lines += ["## Licence texts", "", "### musl libc", "", "```text", MUSL.strip(), "```", ""]
    for h, (t, users) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
        lines += [f'<a id="text-{h}"></a>', "", f"### Text {h}", "", "Used by: " + ", ".join(users) + ".", "",
                  "```text", t.rstrip("\n").replace("```", "'''"), "```", ""]
    return "\n".join(lines), len(crates), missing


def legal_table(meta):
    rows = ["| Crate | Version | Licence | Role | Source |", "|---|---|---|---|---|"]
    for p, role in all_locked(meta):
        rows.append(f"| {p['name']} | {p['version']} | {p.get('license') or '?'} | {role} | {source_url(p)} |")
    return "\n".join(rows)


def main():
    check = "--check" in sys.argv[1:]
    meta = metadata()
    text, n, missing = notices(meta)
    legal = LEGAL.read_text(encoding="utf-8")
    i, j = legal.find(START), legal.find(END)
    if i < 0 or j < 0:
        sys.exit(f"{LEGAL}: markers missing")
    new_legal = legal[: i + len(START)] + "\n\n" + legal_table(meta) + "\n\n" + legal[j:]
    stale = []
    if not NOTICES.exists() or NOTICES.read_text(encoding="utf-8") != text:
        stale.append(NOTICES.name)
    if new_legal != legal:
        stale.append("docs/LEGAL.md")
    if check:
        if stale:
            sys.exit("out of date, run tools/third_party_notices.py: " + ", ".join(stale))
        print("third-party notices up to date")
        return
    NOTICES.write_text(text, encoding="utf-8", newline="\n")
    LEGAL.write_text(new_legal, encoding="utf-8", newline="\n")
    print(f"{n} crates in the binary; without a licence file: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
